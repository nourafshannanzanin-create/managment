function normalizeNameToken(value) {
  return String(value || '')
    .trim()
    .replace(/\u200c/g, '')
    .replace(/ي/g, 'ی')
    .replace(/ك/g, 'ک')
    .split(/\s+/)
    .filter(Boolean)[0] || ''
}

export function inferGenderFromName(fullName) {
  const first = normalizeNameToken(fullName)
  if (!first) return 'unknown'
  if (FEMALE_FIRST_NAMES.has(first)) return 'female'
  if (MALE_FIRST_NAMES.has(first)) return 'male'

  // Soft heuristics for unmarked Persian names
  if (/(ه|یه|ین|ا)$/.test(first) && first.length >= 3 && !MALE_FIRST_NAMES.has(first)) {
    // many female names end with ه؛ keep conservative: only if not clearly male list
    if (/(ه|یه)$/.test(first)) return 'female'
  }
  return 'unknown'
}

export function genderLabel(gender) {
  if (gender === 'female') return 'خانم'
  if (gender === 'male') return 'آقا'
  return ''
}
